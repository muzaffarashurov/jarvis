"""Domain model for EP-028 Agent Framework.

Defines the plain data types shared by `AgentProvider` (lifecycle +
subsystem registry), `AgentEngine` (pipeline orchestration) and
`AgentService` (CLI-facing layer): a single registered subsystem's
diagnostic snapshot (`SubsystemInfo`), the outcome of a single
`execute()` call (`AgentExecutionResult`), and the outcome of a single
`cancel()` call (`AgentCancelResult`). This module owns no lifecycle
logic and no subsystem registry -- it mirrors the role of
`src/core/context_compression/compression_result.py` relative to
`CompressionProvider`/`CompressionEngine`.

The Agent Framework performs no reasoning and no task execution. This
module has no dependency on any LLM, AI provider, prompt, planner, or
reflection component.
"""

from __future__ import annotations

from dataclasses import dataclass

from src.core.agent.agent_state import AgentState

__all__ = [
    "SubsystemInfo",
    "AgentExecutionResult",
    "AgentCancelResult",
]


@dataclass(frozen=True)
class SubsystemInfo:
    """A single registered subsystem's diagnostic snapshot.

    Built by `AgentProvider.list_subsystems()` from whatever was
    handed to `register_subsystem()` -- this type carries no
    reference back to the subsystem's own service/manager/engine, only
    its name and a point-in-time availability flag.

    Attributes:
        name: The subsystem's registered name (e.g. "knowledge",
            "semantic", "compression").
        available: Whether the subsystem currently reports itself
            enabled, per the optional `status_check` callable supplied
            at registration time. True when no `status_check` was
            supplied (a "declared present" subsystem with no live
            binding).
    """

    name: str
    available: bool


@dataclass(frozen=True)
class AgentExecutionResult:
    """The outcome of a single `AgentEngine.execute()` call.

    Since the Agent Framework implements no Planner, Reasoning Engine,
    or Task Scheduler, every `execute()` call completes synchronously
    and immediately -- `dispatched` is always False in this EP; it
    exists so a future Planner-backed `AgentProvider` can report True
    once planning/dispatch is actually implemented, without changing
    this type.

    Attributes:
        request_id: A unique identifier for this request, generated by
            the active `AgentProvider`.
        success: Whether the request was accepted by the agent (not
            whether any task "succeeded" -- no task is executed).
        dispatched: Whether the request was handed to a Planner/Task
            Scheduler for real execution. Always False in this EP.
        state: The agent's `AgentState` immediately after this call
            returned.
        message: Human-readable outcome summary.
    """

    request_id: str
    success: bool
    dispatched: bool
    state: AgentState
    message: str


@dataclass(frozen=True)
class AgentCancelResult:
    """The outcome of a single `AgentEngine.cancel()` call.

    Since every `execute()` call in this EP completes synchronously
    and immediately, there is never anything left running to actually
    cancel -- `success` is always False for a request that is found
    (it already completed), matching the honest scope of an
    orchestration-only Agent Framework with no real task execution.

    Attributes:
        request_id: The request identifier that was requested to be
            cancelled.
        success: Whether the cancellation had any effect. Always False
            in this EP.
        message: Human-readable outcome summary.
    """

    request_id: str
    success: bool
    message: str
